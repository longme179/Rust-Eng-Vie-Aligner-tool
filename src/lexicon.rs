/// Bản đồ tra cứu (build 1 lần).
fn lexicon_map() -> &'static HashMap<&'static str, &'static [&'static str]> {
    static MAP: OnceLock<HashMap<&'static str, &'static [&'static str]>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(EN_VI_LEXICON.len());
        for (en, vi) in EN_VI_LEXICON {
            m.entry(*en).or_insert(*vi); // mục đầu tiên thắng nếu trùng key
        }
        m
    })
}

/// Tra từ điển Anh→Việt (word đã fold, lowercase, không dấu).
pub fn lookup_en(word_folded: &str) -> Option<&'static [&'static str]> {
    lexicon_map().get(word_folded).copied()
}

/// Kiểm tra từ thường gặp (đã fold).
pub fn is_common_word(word_folded: &str) -> bool {
    COMMON_LOWER.iter().any(|w| *w == word_folded)
}
